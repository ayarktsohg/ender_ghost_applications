# ===== ФЛАГИ ФУНКЦИОНАЛА =====

# Конвертировать ли найденные изображения (кроме TIFF и PNG) в PNG?
# При True - все JPG, BMP, GIF и др. будут заменены на PNG
CONVERT_IMAGES_TO_PNG = True  # <- Меняйте здесь!

# Конвертировать ли документы Word (DOC, DOCX) в ODT?
# При True - все DOC и DOCX будут заменены на ODT
