# ===== НАСТРОЙКИ ВЫВОДА =====

# Показывать ли детальную информацию о каждом файле
VERBOSE_OUTPUT = True

# Максимальное количество выводимых различий (чтобы не засорять экран)
MAX_DIFFERENCES_DISPLAY = 100

# ===== НАСТРОЙКИ СРАВНЕНИЯ =====

# Сравнивать ли файлы по содержимому (хешу), а не только по размеру?
# Внимание: при True сравнение будет медленнее для больших файлов
COMPARE_BY_HASH = False

# Игнорировать ли файлы с определёнными расширениями
